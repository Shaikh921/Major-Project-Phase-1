"""
Device Enrollment & Lab PC Lifecycle Models.

Tracks physical workstation registration, cryptographically hashed single-use enrollment codes,
Super Admin approvals, hardware UUIDs, and live connectivity states.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import TYPE_CHECKING, Optional, List
from sqlalchemy import Boolean, DateTime, ForeignKey, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from backend.app.database.base import Base

if TYPE_CHECKING:
    from backend.app.models.user import User
    from backend.app.models.host import Host
    from backend.app.models.agent_key import AgentApiKey


class DeviceStatus(str, Enum):
    """Lifecycle state of an enrolled workstation."""
    PENDING = "PENDING"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    DISABLED = "DISABLED"
    RETIRED = "RETIRED"


class TelemetryHealthStatus(str, Enum):
    """Health classification of reported hardware metrics."""
    HEALTHY = "HEALTHY"
    STALE = "STALE"
    COLLECTION_FAILED = "COLLECTION_FAILED"


class EnrollmentCode(Base):
    """
    Single-use, short-lived enrollment code generated by a Super Admin.
    Raw tokens are NEVER persisted in plaintext; only the SHA-256 hash is stored.
    """
    __tablename__ = "enrollment_codes"

    id: Mapped[int] = mapped_column(primary_key=True, index=True)
    code_hash: Mapped[str] = mapped_column(String(128), unique=True, nullable=False, index=True)
    code_prefix: Mapped[str] = mapped_column(String(16), nullable=False, index=True)
    created_by_user_id: Mapped[int] = mapped_column(Integer, ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    is_used: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False, index=True)
    used_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    revoked_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )

    # Relationships
    created_by: Mapped["User"] = relationship("User")
    enrollments: Mapped[List["DeviceEnrollment"]] = relationship("DeviceEnrollment", back_populates="enrollment_code")


class DeviceEnrollment(Base):
    """
    Enrolled physical workstation record.
    Preserves an immutable internal device UUID that remains constant across
    hostname changes, room moves, and agent updates.
    """
    __tablename__ = "device_enrollments"

    id: Mapped[int] = mapped_column(primary_key=True, index=True)
    device_uuid: Mapped[str] = mapped_column(String(64), unique=True, nullable=False, index=True)
    reported_hostname: Mapped[str] = mapped_column(String(100), nullable=False, index=True)
    assigned_name: Mapped[Optional[str]] = mapped_column(String(100), nullable=True, index=True)
    
    # Physical Location Mapping
    lab_name: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    room_number: Mapped[Optional[str]] = mapped_column(String(50), nullable=True, index=True)
    pc_number: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    
    # Hardware & Network Diagnostics
    ip_address: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    mac_address: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    os_version: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    agent_version: Mapped[Optional[str]] = mapped_column(String(30), nullable=True)

    # Lifecycle State
    status: Mapped[str] = mapped_column(String(30), default=DeviceStatus.PENDING.value, nullable=False, index=True)
    enrollment_code_id: Mapped[Optional[int]] = mapped_column(Integer, ForeignKey("enrollment_codes.id", ondelete="SET NULL"), nullable=True)
    agent_key_id: Mapped[Optional[int]] = mapped_column(Integer, ForeignKey("agent_api_keys.id", ondelete="SET NULL"), nullable=True)
    host_id: Mapped[Optional[int]] = mapped_column(Integer, ForeignKey("hosts.id", ondelete="SET NULL"), nullable=True)
    
    # Audit & Approval Metadata
    requested_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )
    reviewed_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    reviewed_by_user_id: Mapped[Optional[int]] = mapped_column(Integer, ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    rejection_reason: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Health & Connectivity Tracking
    last_contact_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    last_collection_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    last_upload_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    telemetry_health: Mapped[str] = mapped_column(String(30), default=TelemetryHealthStatus.HEALTHY.value, nullable=False)
    queue_backlog: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    
    # Retirement & Uninstallation Flags
    retirement_requested: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    retirement_confirmed: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)

    # One-Time Credential Issuance Delivery Token (Hashed, cleared once retrieved)
    claim_token_hash: Mapped[Optional[str]] = mapped_column(String(128), nullable=True, index=True)
    claim_token_expires_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    pending_raw_key: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    credential_claimed: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)


    # Relationships
    enrollment_code: Mapped[Optional["EnrollmentCode"]] = relationship("EnrollmentCode", back_populates="enrollments")
    agent_key: Mapped[Optional["AgentApiKey"]] = relationship("AgentApiKey")
    host: Mapped[Optional["Host"]] = relationship("Host")
    reviewed_by: Mapped[Optional["User"]] = relationship("User")
