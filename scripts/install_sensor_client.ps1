# PowerShell Windows Agent Installer for CloudOps Intel Lab PC Monitoring
# Architecture: Scheduled Task daemon under NT AUTHORITY\SYSTEM (non-interactive, boots with Windows)

[CmdletBinding()]
param (
    [Parameter(Mandatory = $true, HelpMessage = "CloudOps Intel Server HTTPS URL (e.g. https://10.227.136.246:8443)")]
    [string]$ServerUrl,

    [Parameter(Mandatory = $true, HelpMessage = "Single-use enrollment code generated by Super Admin")]
    [string]$EnrollmentCode,

    [Parameter(Mandatory = $false)]
    [string]$InstallDir = "C:\ProgramData\CloudOpsIntel\Sensor",

    [Parameter(Mandatory = $false)]
    [string]$PythonExe = "",

    [Parameter(Mandatory = $false)]
    [string]$CaCertPath = ""
)

$ErrorActionPreference = "Stop"

Write-Host "==========================================================" -ForegroundColor Cyan
Write-Host " CloudOps Intel — Lab PC Monitoring Agent Installer       " -ForegroundColor Cyan
Write-Host "==========================================================" -ForegroundColor Cyan

# 1. Administrator check
$isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $isAdmin) {
    Write-Warning "Administrative privileges are recommended to install the system-level Scheduled Task and configure secure NTFS ACLs."
}

# 2. Locate Python executable
if (-not $PythonExe) {
    $foundPython = Get-Command "python.exe" -ErrorAction SilentlyContinue
    if ($foundPython) {
        $PythonExe = $foundPython.Source
    } elseif (Test-Path "C:\Python313\python.exe") {
        $PythonExe = "C:\Python313\python.exe"
    } elseif (Test-Path "C:\Python312\python.exe") {
        $PythonExe = "C:\Python312\python.exe"
    } else {
        throw "Could not find python.exe. Please install Python or specify -PythonExe parameter."
    }
}
Write-Host "[*] Using Python: $PythonExe" -ForegroundColor Gray

# 3. Resolve CA bundle
$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
if (-not $CaCertPath) {
    $candidateCert = Join-Path $scriptDir "root.crt"
    if (Test-Path $candidateCert) {
        $CaCertPath = $candidateCert
    } else {
        $candidateCert2 = Join-Path $scriptDir "..\data\caddy\pki\authorities\local\root.crt"
        if (Test-Path $candidateCert2) {
            $CaCertPath = (Resolve-Path $candidateCert2).Path
        }
    }
}

if (-not (Test-Path $CaCertPath)) {
    throw "Server CA certificate (root.crt) not found. Required for strict TLS validation."
}
Write-Host "[*] Verified CA Certificate: $CaCertPath" -ForegroundColor Gray

# 4. Prepare target directory
if (-not (Test-Path $InstallDir)) {
    New-Item -ItemType Directory -Path $InstallDir -Force | Out-Null
    Write-Host "[+] Created install directory: $InstallDir" -ForegroundColor Green
}

# Restrict NTFS ACLs on InstallDir (SYSTEM and Administrators only)
try {
    & icacls "$InstallDir" /inheritance:r /grant:r "SYSTEM:(OI)(CI)F" "Administrators:(OI)(CI)F" | Out-Null
    Write-Host "[+] Applied restrictive NTFS ACLs to $InstallDir" -ForegroundColor Green
} catch {
    Write-Warning "Failed to set strict ACLs on $InstallDir (non-fatal if running as standard user): $_"
}

# 5. Copy agent files
$agentSourceDir = Join-Path $scriptDir "..\monitoring_agent"
if (-not (Test-Path $agentSourceDir)) {
    # If running from extracted zip package
    $agentSourceDir = Join-Path $scriptDir "monitoring_agent"
}

$targetAgentDir = Join-Path $InstallDir "monitoring_agent"
if (-not (Test-Path $targetAgentDir)) {
    New-Item -ItemType Directory -Path $targetAgentDir -Force | Out-Null
}

Copy-Item -Path (Join-Path $agentSourceDir "*") -Destination $targetAgentDir -Recurse -Force
Copy-Item -Path $CaCertPath -Destination (Join-Path $InstallDir "root.crt") -Force
Write-Host "[+] Copied agent binaries and root.crt to $InstallDir" -ForegroundColor Green

# 6. Install Python dependencies (psutil) if missing
Write-Host "[*] Checking Python dependencies..." -ForegroundColor Gray
& $PythonExe -c "import psutil" 2>$null
if ($LASTEXITCODE -ne 0) {
    Write-Host "[*] Installing required psutil telemetry collector package..." -ForegroundColor Yellow
    & $PythonExe -m pip install psutil --quiet
}

# 7. Perform Enrollment Handshake
Write-Host ""
Write-Host "[*] Initiating secure enrollment handshake with $ServerUrl..." -ForegroundColor Cyan
$agentScript = Join-Path $targetAgentDir "agent.py"
$installedCaCert = Join-Path $InstallDir "root.crt"
$configFile = Join-Path $InstallDir "sensor_config.json"
$spoolDb = Join-Path $InstallDir "sensor_spool.db"

$enrollArgs = @(
    "$agentScript",
    "--enroll",
    "--code", "$EnrollmentCode",
    "--server-url", "$ServerUrl",
    "--ca-bundle", "$installedCaCert",
    "--config", "$configFile"
)

& $PythonExe $enrollArgs
if ($LASTEXITCODE -ne 0) {
    throw "Enrollment failed or was rejected. Check server dashboard and enrollment code."
}

if (-not (Test-Path $configFile)) {
    throw "Configuration file was not created after enrollment."
}
Write-Host "[+] Enrollment verified! Sensor configuration saved." -ForegroundColor Green

# 8. Register Windows Scheduled Task
$TaskName = "CloudOpsSensorAgent"
Write-Host ""
Write-Host "[*] Configuring Windows Scheduled Task: $TaskName..." -ForegroundColor Cyan

# Unregister old task if exists
schtasks.exe /Delete /TN $TaskName /F 2>$null

$taskAction = "`"$PythonExe`" `"$agentScript`" --config `"$configFile`" --spool-db `"$spoolDb`""

# Create task to run at startup under SYSTEM (or current user if not admin)
if ($isAdmin) {
    $xmlTask = @"
<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo>
    <Description>CloudOps Intel Workstation Telemetry Sensor Daemon</Description>
    <Author>CloudOps Intel</Author>
  </RegistrationInfo>
  <Triggers>
    <BootTrigger>
      <Enabled>true</Enabled>
    </BootTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author">
      <UserId>S-1-5-18</UserId>
      <RunLevel>HighestAvailable</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <AllowHardTerminate>true</AllowHardTerminate>
    <StartWhenAvailable>true</StartWhenAvailable>
    <RunOnlyIfNetworkAvailable>false</RunOnlyIfNetworkAvailable>
    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>
    <Priority>7</Priority>
    <RestartOnFailure>
      <Interval>PT1M</Interval>
      <Count>3</Count>
    </RestartOnFailure>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>$PythonExe</Command>
      <Arguments>`"$agentScript`" --config `"$configFile`" --spool-db `"$spoolDb`"</Arguments>
      <WorkingDirectory>$InstallDir</WorkingDirectory>
    </Exec>
  </Actions>
</Task>
"@
    $xmlPath = Join-Path $InstallDir "task_def.xml"
    [System.IO.File]::WriteAllText($xmlPath, $xmlTask, [System.Text.Encoding]::Unicode)
    schtasks.exe /Create /TN $TaskName /XML $xmlPath /F | Out-Null
    Remove-Item $xmlPath -Force
} else {
    # Non-admin fallback trigger at logon
    schtasks.exe /Create /TN $TaskName /TR $taskAction /SC ONLOGON /F | Out-Null
}

Write-Host "[+] Registered Windows Scheduled Task: $TaskName (Auto-start on boot)" -ForegroundColor Green

# 9. Start the background sensor task
schtasks.exe /Run /TN $TaskName | Out-Null
Write-Host "[+] Started $TaskName background service." -ForegroundColor Green
Write-Host ""
Write-Host "==========================================================" -ForegroundColor Green
Write-Host " Sensor Agent Installed Successfully!                     " -ForegroundColor Green
Write-Host " Continuous telemetry will be pushed via verified HTTPS.   " -ForegroundColor Green
Write-Host "==========================================================" -ForegroundColor Green
